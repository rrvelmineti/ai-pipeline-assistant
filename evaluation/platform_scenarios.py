def run(database_url=None, performance=False, rows=100_000):
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as tmp:
        settings = Settings(database_url=database_url or f"sqlite:///{Path(tmp).as_posix()}/scenarios.db", storage_dir=f"{tmp}/files",
                            encryption_key=Fernet.generate_key().decode(), web_dist=tmp, export_batch_size=500)
        app = create_app(settings)
        if database_url:
            Base.metadata.drop_all(app.state.engine)
        try:
            with ai_unavailable(), TestClient(app) as client:
                ensure_admin(app.state.Session, "admin", PASSWORD)
                started = time.perf_counter()
                results, _ = run_all(client, PASSWORD, PASSWORD, include_performance=performance, perf_rows=rows)
                results["seconds"] = round(time.perf_counter() - started, 1)
        finally:
            app.state.engine.dispose()
    results["database"] = "postgresql" if database_url and database_url.startswith("postgresql") else "sqlite"
    return results


def traceability(results):
    by_id = {c["id"]: c for s in results["scenarios"] for c in s["checks"]}
    lines = ["# Requirements and UAT traceability", "",
             "Generated by `python -m evaluation.platform_scenarios --save` from a real run; do not edit by hand.",
             f"Run on {results['evaluated_on']} against {results['database']}: "
             f"**{results['checks_passed']} of {results['checks_total']} scenario checks passed.**", "",
             "Scenario checks are listed in full under the table. Automated tests live in `tests/test_platform_*.py`.", "",
             "| Requirement | Proved by scenario checks | Result | Also covered by |", "| --- | --- | --- | --- |"]
    for rid, text, checks, tests in REQUIREMENTS:
        missing = [c for c in checks if c not in by_id]
        if missing:
            raise SystemExit(f"{rid} refers to unknown checks {missing}")
        status = ("Pass" if all(by_id[c]["passed"] for c in checks) else "**Fail**") if checks else "See next column"
        lines.append(f"| **{rid}** {text} | {', '.join(checks) or '–'} | {status} | "
                     f"{'; '.join(f'`{t}`' if t.startswith('test_') else t for t in tests) or '–'} |")
    for s in results["scenarios"]:
        lines += ["", f"## Scenario {s['scenario']}: {s['title']}", "",
                  "| Check | Acceptance criterion | Expected | Actual | Result |", "| --- | --- | --- | --- | --- |"]
        for c in s["checks"]:
            actual = c["actual"].replace("|", "/").replace("\n", " ")[:160]
            lines.append(f"| {c['id']} | {c['criterion']} | {c['expected'] or '–'} | {actual} | "
                         f"{'Pass' if c['passed'] else '**Fail**'} |")
    perf = results.get("performance")
    if perf:
        lines += ["", "## Performance: the largest accepted file", "",
                  f"{perf['rows']:,} synthetic rows ({perf['file_mb']} MB) on {results['database']}, "
                  f"single process on {results['machine']}.", "",
                  "| Step | Result |", "| --- | --- |",
                  f"| Upload and encrypt | {perf['upload_seconds']} s |",
                  f"| Validate every row | {perf['validation_seconds']} s ({perf['validation_rows_per_second']:,} rows per second), decision {perf['decision']} |",
                  f"| Export in {perf['export_batches']} batches | {perf['export_seconds']} s, {perf['records_loaded']:,} records, "
                  f"{perf['distinct_claim_ids']:,} distinct claim IDs |"]
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--performance", action="store_true", help="include the 100,000-row run")
    parser.add_argument("--rows", type=int, default=100_000, help="rows for the performance run")
    parser.add_argument("--database-url", help="PostgreSQL URL; the database is emptied first")
    parser.add_argument("--save", action="store_true", help="write the results file and the traceability matrix")
    args = parser.parse_args(argv)
    results = run(args.database_url, args.performance, args.rows)
    results["evaluated_on"] = date.today().isoformat()
    results["platform_version"] = __version__
    results["machine"] = f"Python {platform.python_version()} on {platform.system()}"
    for s in results["scenarios"]:
        print(f"\nScenario {s['scenario']}: {s['title']}")
        for c in s["checks"]:
            print(f"  {'PASS' if c['passed'] else 'FAIL'}  {c['id']:4} {c['criterion']}  [{c['actual'][:90]}]")
    print(f"\n{results['checks_passed']} of {results['checks_total']} checks passed in {results['seconds']} s "
          f"on {results['database']}.")
    if results.get("performance"):
        p = results["performance"]
        print(f"Performance: {p['rows']:,} rows validated in {p['validation_seconds']} s and exported in "
              f"{p['export_seconds']} s ({p['records_loaded']:,} records loaded).")
    if args.save:
        RESULTS.parent.mkdir(exist_ok=True)
        RESULTS.write_text(json.dumps(results, indent=2, default=str) + "\n", encoding="utf-8")
        TRACE.parent.mkdir(parents=True, exist_ok=True)
        TRACE.write_text(traceability(results), encoding="utf-8")
        print(f"Saved {RESULTS.relative_to(ROOT)} and {TRACE.relative_to(ROOT)}")
    if results["checks_passed"] != results["checks_total"]:
        sys.exit(1)


if __name__ == "__main__":
    main()
